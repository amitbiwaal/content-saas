/**
 * Workspaces Service — `04-platform/workspaces.md`.
 *
 * Increment B: provisioning and lifecycle. Invitations, role changes and
 * membership management beyond the first `workspace_admin` are NOT here.
 *
 * ── Atomicity ────────────────────────────────────────────────────────────────
 * Provisioning writes the workspace, the first `workspace_admin` membership,
 * the initial settings layer, the audit record and the outbox event on ONE
 * transaction handle. "Provisioning partially completes → One transaction;
 * impossible" (§"Failure handling").
 *
 * ── Tenant context ───────────────────────────────────────────────────────────
 * `workspaces.id` IS `tenant_id`, and its RLS policy is
 * `WITH CHECK (id = current_setting('app.tenant_id'))`. So the identifier
 * cannot be generated by the INSERT: the transaction has to already be running
 * under the id being inserted. `workspaceId` is therefore an INPUT, and the
 * caller opens the transaction with
 * `withTenant({ tenantId: workspaceId, organizationId })`.
 *
 * Obtain one from the database's own generator — `SELECT uuidv7()` (migration
 * 0001) — rather than a v4: v7 is time-ordered, so B-tree insertion stays
 * sequential, and `gen_random_uuid()` would silently discard that
 * (`03-database/tables.md` §1.1).
 *
 * The quota count reads across the organization through the second, read-only
 * `workspaces_org_read` policy, which is why `app.organization_id` must be set
 * too. Both settings are established by `withTenant`.
 *
 * ── Quota ────────────────────────────────────────────────────────────────────
 * "Application check inside the creating transaction + advisory lock on
 * `organization_id` to close the race" (`03-database/tables.md` §"Invariants
 * that cannot be enforced declaratively"). The lock is taken BEFORE the count;
 * taking it after would leave exactly the race it exists to close.
 */

