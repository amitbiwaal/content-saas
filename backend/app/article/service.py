def generate_draft(
    outline: dict,
    brief: dict,
    *,
    provider: str = "anthropic",
    research: dict | None = None,
    feedback: str | None = None,
) -> dict:
    """Generate a full draft section by section from an outline (FR-7.2).

    Args:
        outline: Outline payload — an Outline row's ``nodes``/``sections`` tree or
            a bare list of nodes. H2/H3 nodes become body sections (H1 is skipped).
        brief: Project brief (topic/keyword/country/audience/tone/goal).
        provider: Council seat provider name resolved via ``get_adapter``.
        feedback: Optional editor instruction for a review-mode regenerate; woven
            into every section's prompt.

    Returns:
        ``{"sections": [{"heading", "level", "markdown"}, ...], "word_count": int}``
        — JSON-serialisable for the ``draft.sections`` column. ``word_count`` is the
        summed body word count and is always > 0.
    """
    research = research or {}
    parsed = _extract_sections(outline)
    all_headings = [s["heading"] for s in parsed]
    extras = _section_extras(parsed, outline if isinstance(outline, dict) else {}, research, brief)
    rendered = [
        _render_section(s, brief, all_headings, provider, research, feedback, extras[i])
        for i, s in enumerate(parsed)
    ]
    total = sum(s.word_count() for s in rendered)
    return DraftResult(sections=rendered, word_count=total).as_dict()


def _stream_section_body(
    section: dict,
    brief: dict,
    all_headings: list[str],
    provider: str,
    research: dict,
    extra: dict | None = None,
) -> Iterator[dict]:
    """Yield ``{"kind": "delta", "delta": str}`` token chunks for one section body.

    Never raises: a provider refusal/transport error just ends the stream (the
    caller then emits deterministic fallback prose), mirroring the safety contract
    of :func:`_write_section_body` (FR-7.2).
    """
    prompt = _section_prompt(section, brief, all_headings, research, None, extra)
    try:
        stream = get_adapter(provider).stream(
            system=SYSTEM_PROMPT, prompt=prompt, json_mode=False
        )
        for ev in stream:
            if ev.response is not None:
                continue
            if ev.delta:
                yield {"kind": "delta", "delta": ev.delta}
    except (ProviderRefusal, ProviderError):
        return


def stream_draft(
    outline: dict, brief: dict, *, provider: str = "anthropic", research: dict | None = None
) -> Iterator[dict]:
    """Generate a draft section-by-section, streaming tokens live (FR-7.2, §16).

    Sections are written CONCURRENTLY (bounded by :data:`_MAX_SECTION_WORKERS`),
    each streaming into its own slot, so the reader watches the whole article
    fill in at once instead of waiting for one blocking call. Yields:

        {"kind": "section_start", "index", "heading", "level"}
        {"kind": "section_delta", "index", "delta"}                 # a token, live
        {"kind": "section_done",  "index", "heading", "level", "markdown"}
        {"kind": "done", "draft": {"sections": [...], "word_count": int}}  # terminal

    ``section_done.markdown`` is the canonical, JSON-cleaned body — consumers
    should replace (not append) the live text with it. Falls back to deterministic
    prose per section when a seat yields nothing, so the draft is always non-empty
    (zero-API-key contract). Never raises per section: a failed section degrades to
    fallback prose rather than hanging or crashing the draft.
    """
    research = research or {}
    parsed = _extract_sections(outline)
    all_headings = [s["heading"] for s in parsed]
    extras = _section_extras(parsed, outline if isinstance(outline, dict) else {}, research, brief)
    n = len(parsed)
    results: list[Section | None] = [None] * n
    sink: queue.Queue = queue.Queue()

    def worker(index: int, section: dict) -> None:
        acc: list[str] = []
        sink.put({
            "kind": "section_start",
            "index": index,
            "heading": section["heading"],
            "level": section["level"],
        })
        try:
            try:
                for ev in _stream_section_body(
                    section, brief, all_headings, provider, research, extras[index]
                ):
                    acc.append(ev["delta"])
                    sink.put({"kind": "section_delta", "index": index, "delta": ev["delta"]})
                body = _parse_adapter_markdown("".join(acc))
                if _count_words(body) == 0:
                    body = _fallback_markdown(section, brief)
            except Exception:  # noqa: BLE001 - degrade a failed section, never hang
                body = _fallback_markdown(section, brief)
            # Auto-remediate mechanical house-rule triggers (em-dashes, first-person)
            # so the canonical body sent downstream is already publish-clean (PRD §11).
            body = autofix_text(body)
            sec = Section(heading=section["heading"], level=section["level"], markdown=body)
            results[index] = sec
            sink.put({
                "kind": "section_done",
                "index": index,
                "heading": sec.heading,
                "level": sec.level,
                "markdown": sec.markdown,
            })
        finally:
            # Always emitted, even if autofix/Section construction raises, so the
            # consumer's countdown completes and the stream can never hang.
            sink.put({"kind": "__worker_done__"})

    with ThreadPoolExecutor(max_workers=min(_MAX_SECTION_WORKERS, max(1, n))) as pool:
        for i, section in enumerate(parsed):
            pool.submit(worker, i, section)
        remaining = n
        while remaining > 0:
            item = sink.get()
            if item["kind"] == "__worker_done__":
                remaining -= 1
                continue
            yield item

    sections = [s for s in results if s is not None]
    total = sum(s.word_count() for s in sections)
    yield {
        "kind": "done",
        "draft": DraftResult(sections=sections, word_count=total).as_dict(),
    }


def regenerate_section(
    outline: dict,
    brief: dict,
    section_index: int,
    *,
    provider: str = "anthropic",
    research: dict | None = None,
    feedback: str | None = None,
) -> dict:
    """Regenerate a single section of the draft (FR-7.5).

    Args:
        outline: Same outline payload accepted by :func:`generate_draft`.
        brief: Project brief.
        section_index: Zero-based index into the flattened H2/H3 section list.
        provider: Council seat provider name.
        feedback: Optional editor instruction steering the rewrite of this section.

    Returns:
        ``{"heading", "level", "markdown"}`` for the regenerated section.

    Raises:
        IndexError: if ``section_index`` is out of range for the outline.
    """
    research = research or {}
    parsed = _extract_sections(outline)
    if section_index < 0 or section_index >= len(parsed):
        raise IndexError(
            f"section_index {section_index} out of range (0..{len(parsed) - 1})"
        )
    all_headings = [s["heading"] for s in parsed]
    extras = _section_extras(parsed, outline if isinstance(outline, dict) else {}, research, brief)
    section = _render_section(
        parsed[section_index],
        brief,
        all_headings,
        provider,
        research,
        feedback,
        extras[section_index],
    )
    return asdict(section)


# --------------------------------------------------------------------------- #
# Proofreading (copy-edit pass, PRD §7 editable draft)
# --------------------------------------------------------------------------- #
PROOFREAD_SYSTEM = (
    "You are a meticulous copy editor. Correct grammar, spelling, punctuation, "
    "clarity and flow WITHOUT changing meaning, facts, numbers, structure or "
    "Markdown. Keep roughly the same length. Rewrite first-person singular "
    "('I'/'my') to the editorial 'we', and never use em-dashes. Do not add new "
    "claims or remove citations. Return ONLY the corrected Markdown body (no "
    "preamble). If you reply as JSON, use the shape {\"markdown\": str}."
)


def _proofread_one(section: dict, provider: str) -> dict:
    """Copy-edit one section; conservative — keeps the original if unsure.

    Falls back to the original body on provider error, on mock output, or if the
    edit looks destructive (lost more than half the words), so proofreading can
    never gut the draft (and is a safe no-op with zero keys).
    """
    body = section.get("markdown") or ""
    heading = section.get("heading", "")
    level = section.get("level", 2)
    if not body.strip():
        return {"heading": heading, "level": level, "markdown": body}
    try:
        resp = get_adapter(provider).complete(
            system=PROOFREAD_SYSTEM, prompt=body, json_mode=False
        )
        fixed = _parse_adapter_markdown(resp.text)
    except (ProviderRefusal, ProviderError):
        fixed = ""
    if (
        not fixed
        or "[mock:" in fixed
        or _count_words(fixed) < 0.5 * max(1, _count_words(body))
    ):
        fixed = body
    return {"heading": heading, "level": level, "markdown": autofix_text(fixed)}


def proofread_sections(sections: list[dict], *, provider: str = "anthropic") -> list[dict]:
    """Copy-edit every section concurrently, preserving order (FR-7.1)."""
    items = [dict(s) for s in (sections or [])]
    if not items:
        return []
    workers = min(_MAX_SECTION_WORKERS, len(items))
    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(lambda s: _proofread_one(s, provider), items))
