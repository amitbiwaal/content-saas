# small but non-trivial so ``word_count`` is always > 0 even with the mock adapter.
_FALLBACK_BODY_SENTENCES = 3

# How many sections stream concurrently. Bounded so we don't hammer the provider
# or flood the SSE channel, while still writing the article far faster than one
# section at a time (FR-7.2).
_MAX_SECTION_WORKERS = 4


